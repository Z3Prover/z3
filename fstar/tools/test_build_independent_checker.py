"""Fail-closed verified native realizations and extraction fixtures."""

import unittest

from build_independent_checker import prepare_extracted_source


HEADER = '(* Generated by F* Custard extraction. Do not edit. *)\n[@@@ocaml.warning "-3"]\n'
NAME_LENGTH = (
    "let name_length (s : string) : Prims.int =\n"
    "  (count_cells Prims.int_zero "
    "((fun s -> BatList.init (BatUTF8.length s) "
    "(fun i -> BatUChar.code (BatUTF8.get s i))) s))\n")
VARIABLE_LOOKUP = (
    "((Prims.op_Less n (FStar_List_Tot_Base.length scope)) && "
    "((=) (FStar_List_Tot_Base.index scope n) s))")
SCOPE_HELPER = (
    "let matches scope n s =\n"
    f"  (if ((=) n Prims.int_zero) then false else {VARIABLE_LOOKUP})\n")


class NativeNameLengthTests(unittest.TestCase):
    def test_exact_name_count_realization_leaves_other_code_unchanged(self):
        source = HEADER + NAME_LENGTH + "let other = count_cells Prims.int_zero []\n"
        result = prepare_extracted_source("Z3BinderScopeSyntax.ml", source)
        self.assertIn("open Prims\n", result)
        self.assertIn("let name_length (s : string) : Prims.int =\n"
                      "  (FStar_String.strlen s)\n", result)
        self.assertIn("let other = count_cells Prims.int_zero []\n", result)
        self.assertNotIn("BatUTF8", result)

    def test_changed_or_duplicate_binding_stops_the_build(self):
        for body in ("", NAME_LENGTH.replace("Prims.int_zero", "Prims.int_one"),
                     NAME_LENGTH * 2):
            with self.subTest(body=body):
                with self.assertRaisesRegex(RuntimeError, "name_length"):
                    prepare_extracted_source("Z3BinderScopeSyntax.ml", HEADER + body)

    def test_other_modules_keep_their_name_count_and_reject_batteries(self):
        result = prepare_extracted_source("Other.ml", HEADER + NAME_LENGTH)
        self.assertIn("count_cells Prims.int_zero (FStar_String.list_of_string s)", result)
        with self.assertRaisesRegex(RuntimeError, "Batteries"):
            prepare_extracted_source("Other.ml", HEADER + "let f = BatUTF8.length\n")

    def test_verified_context_body_is_inlined_without_a_module_cycle(self):
        source = HEADER + "let contextual_equivalent s t = original s t\n\nlet after = true\n"
        verified = HEADER + ("let contextual_equivalent s t =\n"
                             "  Z3BooleanNormalForm.shape_equal s t\n")
        result = prepare_extracted_source(
            "Z3BooleanNormalForm.ml", source, contextual_source=verified)
        self.assertIn("let contextual_equivalent s t =\n  shape_equal s t\n", result)
        self.assertIn("let after = true\n", result)
        self.assertNotIn("Z3BooleanNormalForm.", result)
        self.assertNotIn("original s t", result)

    def test_context_realization_rejects_missing_or_duplicate_bindings(self):
        source = HEADER + "let contextual_equivalent s t = original s t\n"
        for original, verified in ((source, None), (HEADER, source),
                                   (source, source + source), (source + source, source)):
            with self.subTest(original=original, verified=verified):
                with self.assertRaisesRegex(RuntimeError, "contextual_equivalent"):
                    prepare_extracted_source(
                        "Z3BooleanNormalForm.ml", original, contextual_source=verified)

    def test_scope_lookup_realization_keeps_other_cases(self):
        source = HEADER + f"let scoped scope n s = {VARIABLE_LOOKUP}\nlet other = true\n"
        result = prepare_extracted_source("Z3ExprScope.ml", source, scope_source=HEADER + SCOPE_HELPER)
        self.assertIn(f"(if ((=) n Prims.int_zero) then false else {VARIABLE_LOOKUP})", result)
        self.assertNotIn("Z3IndependentScopeLookup.", result)
        self.assertIn("let other = true\n", result)
        self.assertNotIn("Z3IndependentScopeLookup", prepare_extracted_source("Other.ml", source))

    def test_scope_lookup_rejects_changed_or_duplicate_extraction(self):
        for expression in ("", VARIABLE_LOOKUP.replace(" n ", " m "), VARIABLE_LOOKUP * 2):
            with self.subTest(expression=expression):
                with self.assertRaisesRegex(RuntimeError, "scoped variable lookup"):
                    prepare_extracted_source("Z3ExprScope.ml", HEADER + expression)

    def test_scope_helper_requires_the_original_nonzero_fallback(self):
        body = SCOPE_HELPER
        result = prepare_extracted_source("Z3IndependentScopeLookup.ml", HEADER + body)
        self.assertIn(VARIABLE_LOOKUP, result)
        for invalid in ("", body.replace("Prims.int_zero", "Prims.int_one"), body * 2):
            with self.subTest(invalid=invalid):
                with self.assertRaisesRegex(RuntimeError, "scope lookup fallback"):
                    prepare_extracted_source("Z3IndependentScopeLookup.ml", HEADER + invalid)

    def test_scope_realization_requires_a_single_verified_body(self):
        source = HEADER + f"let scoped scope n s = {VARIABLE_LOOKUP}\n"
        for helper in (None, SCOPE_HELPER * 2, SCOPE_HELPER.replace("let matches", "let rec matches")):
            with self.subTest(helper=helper):
                with self.assertRaisesRegex(RuntimeError, "scope lookup fallback"):
                    prepare_extracted_source("Z3ExprScope.ml", source, scope_source=helper)


if __name__ == "__main__":
    unittest.main()
