"""Prepare 25 UNSAT QF_FF certificate inputs using z3test's exhaustive oracle."""

import argparse
import hashlib
import importlib.util
import itertools
import json
from pathlib import Path
import random
import subprocess

from run_checker_regressions import file_sha256


PRIMES = (2, 3, 5, 7, 17)
PER_FIELD = 5
MAX_ATTEMPTS = 10000
GENERATOR = Path("regressions") / "finite_field" / "test_qfff.py"


def prepare(z3test, output, seed):
    if not seed or "\0" in seed:
        raise ValueError("Sample seed must be nonempty and contain no NUL")
    source = z3test / GENERATOR
    spec = importlib.util.spec_from_file_location("checker_qfff_source", source)
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    commit = subprocess.check_output(
        ["git", "-C", str(z3test), "rev-parse", "HEAD"], text=True).strip()
    output.mkdir(parents=True, exist_ok=False)
    cases = []
    for prime in PRIMES:
        rng = random.Random(f"{seed}\0{prime}")
        seen = set()
        selected = 0
        for attempt in range(MAX_ATTEMPTS):
            formula, evaluate = generator.generate(rng, prime)
            if formula in seen:
                continue
            seen.add(formula)
            if any(evaluate(x, y) for x, y in itertools.product(range(prime), repeat=2)):
                continue
            selected += 1
            relative = f"QF_FF/field-{prime}/case-{selected:02d}.smt2"
            content = ("(set-info :status unsat)\n" +
                       generator.problem(prime, formula)).encode("utf-8")
            path = output / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            cases.append({
                "path": relative, "logic": "QF_FF", "prime": prime,
                "attempt": attempt + 1, "sha256": hashlib.sha256(content).hexdigest(),
            })
            if selected == PER_FIELD:
                break
        if selected != PER_FIELD:
            raise ValueError(
                f"QF_FF({prime}): requested {PER_FIELD} distinct UNSAT inputs, "
                f"only {selected} found in {MAX_ATTEMPTS} attempts")
        print(f"QF_FF({prime}): selected {selected} exhaustively UNSAT inputs", flush=True)
    document = {
        "schema_version": 1,
        "source": f"https://github.com/Z3Prover/z3test/blob/{commit}/{GENERATOR.as_posix()}",
        "seed": seed, "per_logic": {"QF_FF": len(PRIMES) * PER_FIELD},
        "selection": "Five distinct formulas per prime (2, 3, 5, 7, 17), generated by "
                     "z3test and exhaustively UNSAT over every assignment to x and y; "
                     "no solver or checker outcome is used for selection",
        "generators": [{
            "logic": "QF_FF", "path": GENERATOR.as_posix(),
            "commit": commit, "sha256": file_sha256(source),
        }],
        "cases": sorted(cases, key=lambda case: case["path"]),
    }
    (output / "manifest.json").write_text(
        json.dumps(document, indent=2) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--z3test", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True, help="New input directory")
    parser.add_argument("--seed", required=True)
    args = parser.parse_args()
    prepare(args.z3test, args.output, args.seed)


if __name__ == "__main__":
    main()
