"""Build the calibrated ``eval`` and ``hard`` benchmark tiers.

Why calibration instead of hand-picked sizes
--------------------------------------------
The ``smoke`` tier written by ``gen_benchmarks.py`` solves in single-digit
milliseconds.  That is fine for correctness tests, but useless for evaluating
a parallel *anytime* solver: every configuration finishes before parallelism,
information sharing, or a bound trajectory can matter.

This script therefore *measures* rather than guesses.  Each family exposes one
scalar difficulty knob.  For a given (family, weighted) slot the script runs a
bisection on that knob, timing how long ``z3.Optimize`` needs to prove
optimality:

* measured time inside ``[--target-min, --target-max]`` (default 1s..30s)
  -> retained in the ``eval`` tier;
* still running at the search timeout -> the knob is too high, so bisect down;
  the first such candidate per slot is re-measured at the full
  ``--probe-timeout`` and, if it still cannot be closed, retained in the
  ``hard`` tier with ``known_optimum: null`` plus the best cost Z3 reached as
  ``best_known_cost``;
* solved far too quickly -> the knob is too low, so bisect up.

Bisection matters here.  A fixed size ladder overshoots badly: for several
families -- especially the *unweighted* ones, where uniform weights create ties
and symmetry that make a proof of optimality much harder -- the gap between
"milliseconds" and "beyond 60 seconds" is narrow, and a coarse ladder steps
straight over the target window.

Because instances are selected *on the observed outcome*, the retained ``eval``
tier lands in the target window by construction.  Run-to-run variance only
changes which candidates survive, never that survivors were measured in range.

Everything is seeded, and accepted (family, knob, seed) triples are written to
``calibration.json`` so the tiers can be regenerated elsewhere.  Timings are
machine specific; see the README.
"""
from __future__ import annotations

import argparse
import itertools
import json
import random
import time
from pathlib import Path
from typing import Any, Callable

import z3

ROOT = Path(__file__).resolve().parent
LOCAL = ROOT / "local"
CALIBRATION = ROOT / "calibration.json"

DEFAULT_SEED = 20260813
DEFAULT_PROBE_TIMEOUT = 60.0
DEFAULT_TARGET_MIN = 1.0
DEFAULT_TARGET_MAX = 30.0
DEFAULT_BUDGET = 1200.0
DEFAULT_EVAL_PER_SLOT = 2
DEFAULT_HARD_TARGET = 5
DEFAULT_MAX_PROBES = 7

FAMILIES = ("random_2sat", "random_3sat", "vertex_cover", "set_cover", "lia", "scheduling")


# --------------------------------------------------------------------------
# instance generators
#
# Every generator is a pure function of (params, seed, weighted) returning
# WCNF/SMT-LIB2 text.  The leading ``c family=... weighted=...`` marker is the
# metadata line that ``make_manifest.py`` parses.
# --------------------------------------------------------------------------

def _lits(rng: random.Random, nvars: int, width: int) -> list[int]:
    variables = rng.sample(range(1, nvars + 1), width)
    return [v if rng.randrange(2) else -v for v in variables]


def _weight(rng: random.Random, weighted: bool) -> int:
    return rng.randint(1, 9) if weighted else 1


def _emit_wcnf(family: str, weighted: bool, params: dict[str, Any], seed: int,
               hard: list[list[int]], soft: list[tuple[int, list[int]]]) -> str:
    note = " ".join(f"{k}={v}" for k, v in sorted(params.items()))
    lines = [
        f"c family={family} weighted={str(weighted).lower()} {note} seed={seed}".rstrip(),
        "c generated by calibrate.py; revised DIMACS WCNF",
        "c h marks a hard clause; an integer prefix is a soft weight",
    ]
    lines += [f"h {' '.join(map(str, clause))} 0" for clause in hard]
    lines += [f"{w} {' '.join(map(str, clause))} 0" for w, clause in soft]
    return "\n".join(lines) + "\n"


def gen_random_sat(width: int) -> Callable[..., str]:
    """Random Max-k-SAT at the classic transition ratio (1.0 / 4.2)."""
    ratio = 1.0 if width == 2 else 4.2
    family = f"random_{width}sat"

    def generate(params: dict[str, Any], seed: int, weighted: bool) -> str:
        rng = random.Random(seed)
        nvars = int(params["nvars"])
        soft = [(_weight(rng, weighted), _lits(rng, nvars, width)) for _ in range(int(ratio * nvars))]
        return _emit_wcnf(family, weighted, params, seed, [], soft)

    return generate


def _structured(family: str, structure) -> Callable[..., str]:
    """Structured family plus a tunable random Max-3-SAT overlay.

    Pure minimum vertex cover / set cover / interval scheduling encodings stay
    trivial for Z3 even at thousands of variables because the structure is
    easy.  ``noise`` mixes in random 3-clauses over the same variables and is
    the knob that actually moves solve time, so the search bisects on it.
    """

    def generate(params: dict[str, Any], seed: int, weighted: bool) -> str:
        rng = random.Random(seed)
        nvars = int(params["nvars"])
        hard, soft = structure(rng, nvars, weighted)
        for _ in range(int(float(params.get("noise", 0.0)) * nvars)):
            soft.append((_weight(rng, weighted), _lits(rng, nvars, 3)))
        return _emit_wcnf(family, weighted, params, seed, hard, soft)

    return generate


def _vertex_cover(rng: random.Random, nvars: int, weighted: bool):
    hard = []
    for u in range(1, nvars + 1):
        for v in range(u + 1, nvars + 1):
            if rng.random() < 0.15:
                hard.append([u, v])
    return hard, [(_weight(rng, weighted), [-v]) for v in range(1, nvars + 1)]


def _set_cover(rng: random.Random, nvars: int, weighted: bool):
    universe = list(range(max(2, nvars // 2)))
    members = [set(rng.sample(universe, rng.randint(3, min(8, len(universe))))) for _ in range(nvars)]
    for element in universe:
        if not any(element in s for s in members):
            members[rng.randrange(nvars)].add(element)
    hard = [[i + 1 for i, s in enumerate(members) if element in s] for element in universe]
    return hard, [(_weight(rng, weighted), [-(i + 1)]) for i in range(nvars)]


def _scheduling(rng: random.Random, nvars: int, weighted: bool):
    intervals = []
    for _ in range(nvars):
        start = rng.randrange(4 * nvars)
        intervals.append((start, start + rng.randint(2, 9)))
    hard = []
    for i, j in itertools.combinations(range(nvars), 2):
        if intervals[i][0] < intervals[j][1] and intervals[j][0] < intervals[i][1]:
            hard.append([-(i + 1), -(j + 1)])
    return hard, [(_weight(rng, weighted), [i + 1]) for i in range(nvars)]


def gen_lia(params: dict[str, Any], seed: int, weighted: bool) -> str:
    """Bounded QF_LIA: genuinely non-Boolean MaxSMT, not MaxSAT in disguise."""
    rng = random.Random(seed)
    nvars = int(params["nvars"])
    note = " ".join(f"{k}={v}" for k, v in sorted(params.items()))
    lines = [
        f"; family=lia weighted={str(weighted).lower()} {note} seed={seed}".rstrip(),
        "; generated by calibrate.py",
        "(set-logic QF_LIA)",
    ]
    for i in range(nvars):
        lines.append(f"(declare-const x{i} Int)")
        lines.append(f"(assert (and (>= x{i} 0) (<= x{i} {2 * nvars})))")
    lines.append("(assert (= (+ " + " ".join(f"x{i}" for i in range(nvars)) + f") {nvars * nvars}))")
    constraints = [f"(= x{i} {rng.randrange(2 * nvars + 1)})" for i in range(nvars)]
    constraints += [f"(<= (+ (* 2 x{2 * i}) x{2 * i + 1}) {2 * nvars})" for i in range(nvars // 2)]
    for formula in constraints:
        lines.append(f"(assert-soft {formula} :weight {_weight(rng, weighted)})")
    lines.append("(check-sat)")
    return "\n".join(lines) + "\n"


# One scalar difficulty knob per family, with bounds and a starting guess.
# ``fixed`` holds the non-searched parameters.
#
# For the structured families the knob is the instance size, not the random
# overlay: unweighted minimum vertex cover / set cover are already hard to
# close at a few hundred variables even with no noise at all, so sweeping the
# overlay there only produces timeouts.  A small fixed overlay keeps the
# instances from being pure covering problems.
SEARCH: dict[str, dict[str, Any]] = {
    "random_2sat": {
        "generate": gen_random_sat(2), "suffix": ".wcnf",
        "knob": "nvars", "integral": True, "lo": 2000, "hi": 200000, "start": 40000, "fixed": {},
    },
    "random_3sat": {
        "generate": gen_random_sat(3), "suffix": ".wcnf",
        "knob": "nvars", "integral": True, "lo": 60, "hi": 600, "start": 220, "fixed": {},
    },
    "vertex_cover": {
        "generate": _structured("vertex_cover", _vertex_cover), "suffix": ".wcnf",
        "knob": "nvars", "integral": True, "lo": 15, "hi": 400, "start": 70, "fixed": {"noise": 0.5},
    },
    "set_cover": {
        "generate": _structured("set_cover", _set_cover), "suffix": ".wcnf",
        "knob": "nvars", "integral": True, "lo": 15, "hi": 400, "start": 70, "fixed": {"noise": 0.5},
    },
    "scheduling": {
        "generate": _structured("scheduling", _scheduling), "suffix": ".wcnf",
        "knob": "nvars", "integral": True, "lo": 20, "hi": 600, "start": 150, "fixed": {"noise": 1.5},
    },
    "lia": {
        "generate": gen_lia, "suffix": ".smt2",
        "knob": "nvars", "integral": True, "lo": 30, "hi": 1200, "start": 250, "fixed": {},
    },
}


# --------------------------------------------------------------------------
# measurement
# --------------------------------------------------------------------------

def _integer(value: z3.ExprRef) -> int | None:
    if z3.is_int_value(value):
        return value.as_long()
    if z3.is_rational_value(value) and value.denominator_as_long() == 1:
        return value.numerator_as_long()
    return None


def measure(path: Path, timeout_seconds: float) -> dict[str, Any]:
    """Time a proof of optimality for one instance in a private context.

    ``status`` is ``optimal`` (proved within the timeout), ``timeout`` (still
    open when the timeout fired, with the incumbent kept as ``best_known_cost``)
    or ``error``.
    """
    from parse import parse_file  # local import keeps this module standalone

    ctx = z3.Context()  # a fresh context per probe keeps measurements independent
    problem = parse_file(path, ctx=ctx)
    opt = z3.Optimize(ctx=ctx)
    opt.set(timeout=max(1, int(timeout_seconds * 1000)))
    if problem.hard:
        opt.add(*problem.hard)
    terms = [z3.If(f, z3.IntVal(0, ctx=ctx), z3.IntVal(w, ctx=ctx)) for f, w in problem.soft]
    objective = z3.Sum(terms) if terms else z3.IntVal(0, ctx=ctx)
    handle = opt.minimize(objective)

    started = time.perf_counter()
    try:
        result = opt.check()
    except z3.Z3Exception as exc:
        return {"status": "error", "seconds": time.perf_counter() - started, "note": str(exc)}
    elapsed = time.perf_counter() - started

    if result == z3.sat:
        value = None
        try:
            value = _integer(opt.lower(handle))
        except z3.Z3Exception:
            value = None
        if value is None:
            try:
                value = _integer(opt.model().eval(objective, model_completion=True))
            except z3.Z3Exception:
                value = None
        return {"status": "optimal", "seconds": elapsed, "known_optimum": value}

    best = None
    try:
        best = _integer(opt.model().eval(objective, model_completion=True))
    except z3.Z3Exception:
        best = None
    return {"status": "timeout", "seconds": elapsed, "best_known_cost": best}


# --------------------------------------------------------------------------
# bisection sweep
# --------------------------------------------------------------------------

def calibrate(*, seed: int, budget: float, probe_timeout: float, target_min: float,
              target_max: float, eval_per_slot: int, hard_target: int,
              max_probes: int, slots: list[tuple[str, bool]] | None = None,
              existing: dict[str, Any] | None = None) -> dict[str, Any]:
    LOCAL.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    # When merging, seed the accumulators from the prior run so already-accepted
    # instances (and the hard quota they filled) are preserved rather than redone.
    accepted: list[dict[str, Any]] = list(existing["instances"]) if existing else []
    attempts: list[dict[str, Any]] = list(existing["attempts"]) if existing else []
    hard_count = sum(1 for i in accepted if i["tier"] == "hard")
    eval_by_slot: dict[tuple[str, bool], int] = {}
    for inst in accepted:
        if inst["tier"] == "eval":
            eval_by_slot[(inst["family"], inst["weighted"])] = eval_by_slot.get((inst["family"], inst["weighted"]), 0) + 1
    # Searching only needs to distinguish "inside the window" from "past it",
    # so probes use a tighter timeout; the full budget is spent only when
    # confirming a hard-tier instance.
    search_timeout = min(probe_timeout, target_max + 5.0)

    def remaining() -> float:
        return budget - (time.perf_counter() - started)

    if slots is None:
        slots = [(family, weighted) for weighted in (False, True) for family in FAMILIES]
    for family, weighted in slots:
            already = eval_by_slot.get((family, weighted), 0)
            if already >= eval_per_slot:
                # Slot already satisfied by a prior run; skip to save budget.
                continue
            spec = SEARCH[family]
            tag = "w" if weighted else "u"
            knob = spec["knob"]
            lo_bound, hi_bound = float(spec["lo"]), float(spec["hi"])
            too_easy: float | None = None   # largest knob value known to be too fast
            too_hard: float | None = None   # smallest knob value known to be too slow
            x = float(spec["start"])
            kept = 0
            hard_tried = False
            probed_values: set[float] = set()

            for probe in range(max_probes):
                if kept >= eval_per_slot:
                    break
                if remaining() <= search_timeout * 0.6:
                    print(f"  budget exhausted ({remaining():.0f}s left); stopping slot", flush=True)
                    kept = -1  # sentinel: budget ran out, abort remaining slots
                    break

                value = int(round(x)) if spec["integral"] else round(x, 3)
                if value in probed_values:
                    # The knob has been clamped against a bound or the bracket
                    # has collapsed; re-measuring the identical instance would
                    # only burn budget.
                    print(f"  {family:<13}{tag} {knob}={value:<9} exhausted (knob pinned)", flush=True)
                    break
                probed_values.add(value)
                params = dict(spec["fixed"]); params[knob] = value
                probe_seed = seed + probe * 7919 + (104729 if weighted else 0) + sum(map(ord, family))
                stem = f"cal_{family}_{tag}_{probe}"
                path = LOCAL / f"{stem}{spec['suffix']}"
                path.write_text(spec["generate"](params, probe_seed, weighted), encoding="utf-8")

                outcome = measure(path, search_timeout)
                attempts.append({
                    "family": family, "weighted": weighted, "params": params, "seed": probe_seed,
                    "status": outcome["status"], "seconds": round(outcome["seconds"], 3),
                })
                print(f"  {family:<13}{tag} {knob}={value:<9} {outcome['status']:<8} "
                      f"{outcome['seconds']:6.2f}s", flush=True)

                if outcome["status"] == "optimal" and target_min <= outcome["seconds"] <= target_max:
                    final = LOCAL / f"eval_{family}_{tag}_{probe}{spec['suffix']}"
                    path.replace(final)
                    accepted.append({
                        "path": f"local/{final.name}", "tier": "eval", "family": family,
                        "weighted": weighted, "params": params, "seed": probe_seed,
                        "measured_seconds": round(outcome["seconds"], 3),
                        "known_optimum": outcome.get("known_optimum"),
                        "measured_with_timeout_seconds": search_timeout,
                    })
                    kept += 1
                    # Look for a second, harder point in the same window.
                    too_easy = x
                    x = min(hi_bound, x * 1.35) if too_hard is None else (x + too_hard) / 2.0
                    continue

                if outcome["status"] == "optimal":
                    # Proved, but faster than the window: knob is too low.
                    too_easy = x
                    path.unlink(missing_ok=True)
                    x = min(hi_bound, x * 2.0) if too_hard is None else (x + too_hard) / 2.0
                else:
                    # Past the window.  Bank the first such candidate per slot
                    # as a hard-tier instance, confirmed at the full timeout.
                    too_hard = x
                    banked = False
                    if hard_count < hard_target and not hard_tried and remaining() > probe_timeout:
                        hard_tried = True
                        confirm = measure(path, probe_timeout)
                        attempts.append({
                            "family": family, "weighted": weighted, "params": params,
                            "seed": probe_seed, "status": f"hard-confirm:{confirm['status']}",
                            "seconds": round(confirm["seconds"], 3),
                        })
                        print(f"    hard-confirm @{probe_timeout:g}s -> {confirm['status']} "
                              f"{confirm['seconds']:.2f}s", flush=True)
                        if confirm["status"] == "timeout":
                            final = LOCAL / f"hard_{family}_{tag}_{probe}{spec['suffix']}"
                            path.replace(final)
                            accepted.append({
                                "path": f"local/{final.name}", "tier": "hard", "family": family,
                                "weighted": weighted, "params": params, "seed": probe_seed,
                                "measured_seconds": round(confirm["seconds"], 3),
                                "known_optimum": None,
                                "best_known_cost": confirm.get("best_known_cost"),
                                "measured_with_timeout_seconds": probe_timeout,
                            })
                            hard_count += 1
                            banked = True
                    if not banked:
                        path.unlink(missing_ok=True)
                    x = max(lo_bound, x / 2.0) if too_easy is None else (x + too_easy) / 2.0

                # Bracket collapsed: no useful knob value left to try.
                if too_easy is not None and too_hard is not None:
                    gap = abs(too_hard - too_easy)
                    if gap <= (1.0 if spec["integral"] else 0.02):
                        break

            if kept == -1:
                # Budget exhausted mid-slot; stop launching further slots.
                break

    wall = time.perf_counter() - started
    record = {
        "generated_by": "calibrate.py",
        "seed": seed,
        "probe_timeout_seconds": probe_timeout,
        "search_timeout_seconds": search_timeout,
        "target_window_seconds": [target_min, target_max],
        "sweep_wall_seconds": round(wall, 2),
        "attempts": attempts,
        "instances": accepted,
    }
    CALIBRATION.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return record


def summarize(record: dict[str, Any]) -> None:
    instances = record["instances"]
    print()
    print(f"sweep wall time: {record['sweep_wall_seconds']:.1f}s over {len(record['attempts'])} probes")
    for tier in ("eval", "hard"):
        rows = [i for i in instances if i["tier"] == tier]
        if not rows:
            print(f"{tier}: 0 instances")
            continue
        times = [i["measured_seconds"] for i in rows]
        families = sorted({i["family"] for i in rows})
        weighted = sum(1 for i in rows if i["weighted"])
        print(f"{tier}: {len(rows)} instances ({weighted} weighted, {len(rows) - weighted} unweighted), "
              f"measured {min(times):.2f}s..{max(times):.2f}s")
        print(f"      families: {', '.join(families)}")
        for row in rows:
            extra = (f"optimum={row['known_optimum']}" if tier == "eval"
                     else f"best_known_cost={row.get('best_known_cost')}")
            print(f"    {row['path']:<42}{row['measured_seconds']:7.2f}s  {extra}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--budget", type=float, default=DEFAULT_BUDGET,
                        help="wall-clock cap for the whole sweep in seconds (default: 1200)")
    parser.add_argument("--probe-timeout", type=float, default=DEFAULT_PROBE_TIMEOUT,
                        help="timeout used to confirm a hard-tier instance (default: 60)")
    parser.add_argument("--target-min", type=float, default=DEFAULT_TARGET_MIN)
    parser.add_argument("--target-max", type=float, default=DEFAULT_TARGET_MAX)
    parser.add_argument("--eval-per-slot", type=int, default=DEFAULT_EVAL_PER_SLOT,
                        help="eval instances to keep per (family, weighted) slot")
    parser.add_argument("--hard-target", type=int, default=DEFAULT_HARD_TARGET)
    parser.add_argument("--max-probes", type=int, default=DEFAULT_MAX_PROBES,
                        help="bisection probes per (family, weighted) slot")
    parser.add_argument("--merge", action="store_true",
                        help="keep instances already in calibration.json and only fill missing slots")
    parser.add_argument("--families", default="",
                        help="comma-separated family filter (default: all)")
    parser.add_argument("--weighted", choices=("both", "true", "false"), default="both",
                        help="restrict to weighted/unweighted slots (default: both)")
    args = parser.parse_args()
    if args.target_min <= 0 or args.target_max <= args.target_min:
        parser.error("require 0 < --target-min < --target-max")

    families = [f.strip() for f in args.families.split(",") if f.strip()] or list(FAMILIES)
    unknown = [f for f in families if f not in FAMILIES]
    if unknown:
        parser.error(f"unknown families: {unknown}")
    weight_opts = {"both": (False, True), "true": (True,), "false": (False,)}[args.weighted]
    slots = [(family, weighted) for weighted in weight_opts for family in families]

    existing = None
    if args.merge and CALIBRATION.exists():
        existing = json.loads(CALIBRATION.read_text(encoding="utf-8"))
        print(f"merge mode: preserving {len(existing['instances'])} existing instances")

    print(f"calibrating tiers: window [{args.target_min:g}s, {args.target_max:g}s], "
          f"hard timeout {args.probe_timeout:g}s, budget {args.budget:g}s, "
          f"{len(slots)} slot(s)")
    record = calibrate(
        seed=args.seed, budget=args.budget, probe_timeout=args.probe_timeout,
        target_min=args.target_min, target_max=args.target_max,
        eval_per_slot=args.eval_per_slot, hard_target=args.hard_target,
        max_probes=args.max_probes, slots=slots, existing=existing,
    )
    summarize(record)
    print(f"\nwrote {CALIBRATION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
