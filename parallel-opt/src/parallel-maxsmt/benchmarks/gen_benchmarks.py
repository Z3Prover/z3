"""Generate a deterministic, small local benchmark portfolio.

The generator intentionally writes only under ``local/`` next to this file.
Each family has two seeds and both an unweighted and weighted variant, giving
24 instances (six families x two seeds x two weighting modes).
"""
from __future__ import annotations

import argparse
import itertools
import random
from pathlib import Path
from typing import Iterable

ROOT = Path(__file__).resolve().parent
LOCAL = ROOT / "local"
DEFAULT_SEED = 20260813


def _clause_text(lits: Iterable[int]) -> str:
    return " ".join(str(v) for v in lits)


def _write_wcnf(
    path: Path,
    family: str,
    seed: int,
    weighted: bool,
    nvars: int,
    hard: list[list[int]],
    soft: list[tuple[int, list[int]]],
    note: str = "",
) -> None:
    lines = [
        f"c generated by gen_benchmarks.py seed={seed}",
        f"c family={family} weighted={str(weighted).lower()} {note}".rstrip(),
        "c revised DIMACS WCNF: h marks hard clauses; integer prefixes are soft weights",
    ]
    lines.extend(f"h {_clause_text(clause)} 0" for clause in hard)
    lines.extend(f"{weight} {_clause_text(clause)} 0" for weight, clause in soft)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _random_clause(rng: random.Random, nvars: int, width: int) -> list[int]:
    variables = rng.sample(range(1, nvars + 1), width)
    return [v if rng.randrange(2) else -v for v in variables]


def _random_sat(rng: random.Random, width: int, weighted: bool, seed: int) -> tuple[int, list[list[int]], list[tuple[int, list[int]]], str]:
    # Ratios 1.0 (2-SAT) and 4.2 (3-SAT) are the classic random-SAT
    # transition neighborhoods.  These remain intentionally small for local
    # exact evaluation.
    nvars = 16 if width == 2 else 18
    nsoft = nvars if width == 2 else int(4.2 * nvars)
    soft = []
    for _ in range(nsoft):
        weight = rng.randint(1, 5) if weighted else 1
        soft.append((weight, _random_clause(rng, nvars, width)))
    return nvars, [], soft, f"width={width} ratio={nsoft / nvars:.2f}"


def _vertex_cover(rng: random.Random, weighted: bool, seed: int) -> tuple[int, list[list[int]], list[tuple[int, list[int]]], str]:
    nvars = 12
    edges: list[tuple[int, int]] = []
    for u in range(1, nvars + 1):
        for v in range(u + 1, nvars + 1):
            if rng.random() < 0.30:
                edges.append((u, v))
    if not edges:
        edges = [(u, u + 1) for u in range(1, nvars)]
    hard = [[u, v] for u, v in edges]
    soft = [((rng.randint(1, 5) if weighted else 1), [-v]) for v in range(1, nvars + 1)]
    return nvars, hard, soft, f"edges={len(edges)} encoding=minimum-vertex-cover"


def _set_cover(rng: random.Random, weighted: bool, seed: int) -> tuple[int, list[list[int]], list[tuple[int, list[int]]], str]:
    universe = list(range(9))
    nsets = 14
    members: list[set[int]] = []
    for i in range(nsets):
        members.append(set(rng.sample(universe, rng.randint(2, 4))))
    # Guarantee that every element is covered by at least one selectable set.
    for element in universe:
        if not any(element in members[i] for i in range(nsets)):
            members[element % nsets].add(element)
    hard = []
    for element in universe:
        hard.append([i + 1 for i, elems in enumerate(members) if element in elems])
    soft = [((rng.randint(1, 5) if weighted else 1), [-(i + 1)]) for i in range(nsets)]
    return nsets, hard, soft, f"universe={len(universe)} sets={nsets} encoding=set-cover"


def _lia_text(rng: random.Random, weighted: bool, seed: int) -> str:
    # Bounded integer variables and linear relations keep the objective finite
    # while requiring arithmetic reasoning rather than Boolean SAT alone.
    nvars = 3
    total = 10 + seed
    targets = [2 + seed, 5 - seed, 3]
    lines = [
        "; generated by gen_benchmarks.py",
        f"; family=lia weighted={str(weighted).lower()} seed={seed} encoding=QF_LIA",
        "(set-logic QF_LIA)",
    ]
    lines.extend(f"(declare-const x{i} Int)" for i in range(nvars))
    for i in range(nvars):
        lines.append(f"(assert (and (>= x{i} 0) (<= x{i} 12)))")
    lines.append(f"(assert (= (+ x0 x1 x2) {total}))")
    constraints = [
        f"(= x0 {targets[0]})",
        f"(= x1 {targets[1]})",
        f"(= x2 {targets[2]})",
        "(<= (+ (* 2 x0) x1) 13)",
        "(<= (+ x1 (* 2 x2)) 12)",
    ]
    for formula in constraints:
        weight = rng.randint(1, 5) if weighted else 1
        lines.append(f"(assert-soft {formula} :weight {weight})")
    lines.append("(check-sat)")
    return "\n".join(lines) + "\n"


def _scheduling(rng: random.Random, weighted: bool, seed: int) -> tuple[int, list[list[int]], list[tuple[int, list[int]]], str]:
    nvars = 10
    intervals: list[tuple[int, int]] = []
    for _ in range(nvars):
        start = rng.randint(0, 16)
        duration = rng.randint(2, 5)
        intervals.append((start, start + duration))
    hard: list[list[int]] = []
    for i, j in itertools.combinations(range(nvars), 2):
        si, ei = intervals[i]
        sj, ej = intervals[j]
        if si < ej and sj < ei:
            # At most one of two overlapping jobs is selected.
            hard.append([-(i + 1), -(j + 1)])
    soft = []
    for i, (start, end) in enumerate(intervals):
        priority = 1 + ((i * 3 + seed) % 5)
        soft.append(((priority if weighted else 1), [i + 1]))
    return nvars, hard, soft, f"jobs={nvars} conflicts={len(hard)} encoding=interval-scheduling"


def generate(seed: int = DEFAULT_SEED) -> list[Path]:
    LOCAL.mkdir(parents=True, exist_ok=True)
    # Each output name has a stable seed derived from the requested seed.
    written: list[Path] = []
    # Two seeds per family produce reproducible but distinct instances.
    for family in ("random_2sat", "random_3sat", "vertex_cover", "set_cover", "lia", "scheduling"):
        for instance_seed in (0, 1):
            for weighted in (False, True):
                # Do not use Python's process-randomized hash here: the
                # arithmetic family code keeps output byte-for-byte stable.
                stable_code = sum((i + 1) * ord(ch) for i, ch in enumerate(family))
                rng = random.Random(seed + stable_code * 1009 + instance_seed * 9176 + int(weighted))
                stem = f"gen_{family}_{instance_seed}_{'w' if weighted else 'u'}"
                if family == "lia":
                    path = LOCAL / f"{stem}.smt2"
                    path.write_text(_lia_text(rng, weighted, instance_seed), encoding="utf-8")
                else:
                    if family == "random_2sat":
                        data = _random_sat(rng, 2, weighted, instance_seed)
                    elif family == "random_3sat":
                        data = _random_sat(rng, 3, weighted, instance_seed)
                    elif family == "vertex_cover":
                        data = _vertex_cover(rng, weighted, instance_seed)
                    elif family == "set_cover":
                        data = _set_cover(rng, weighted, instance_seed)
                    elif family == "scheduling":
                        data = _scheduling(rng, weighted, instance_seed)
                    else:  # pragma: no cover - closed family list above
                        raise AssertionError(family)
                    nvars, hard, soft, note = data
                    path = LOCAL / f"{stem}.wcnf"
                    _write_wcnf(path, family, instance_seed, weighted, nvars, hard, soft, note)
                written.append(path)
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED, help="deterministic generator seed")
    args = parser.parse_args()
    paths = generate(args.seed)
    print(f"generated {len(paths)} instances under {LOCAL}")
    for path in paths:
        print(f"  {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
